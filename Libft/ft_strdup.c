#include "libft.h"

char	*ft_strdup(const char *s1)
{
	size_t	s1_len;
	char	*copy;
	size_t	i;

	s1_len = ft_strlen(s1) + 1;
	copy = (char *)ft_calloc(s1_len, 1);
	if (copy == NULL)
		return (NULL);
	i = 0;
	while (s1[i] != '\0')
	{
		copy[i] = s1[i];
		i++;
	}
	copy[i] = '\0';
	return (copy);
}
